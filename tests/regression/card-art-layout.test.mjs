test('opaque subject bounds land at the shared card-window and collection centers', async () => {
  const source = await loadJson(resolve(assetsRoot, 'card-art-layouts.json'));
  const cards = await loadJson(resolve(GAME_ROOT, 'content/cards.json'));
  for (const card of cards) {
    const row = source.assets[card.visual.icon];
    assert.ok(row, card.id);
    const centerX = (row.bbox32[0] + row.bbox32[2]) / 2 / row.size[0];
    const centerY = (row.bbox32[1] + row.bbox32[3]) / 2 / row.size[1];
    for (const context of ['full', 'collection']) {
      const layout = getCardArtLayout(card.visual, context);
      assert.ok(Math.abs(centerX + layout.offsetX / 100 - .5) < .00002, `${card.id}: x drift`);
      assert.ok(Math.abs(centerY + layout.offsetY / 100 - .5) < .00002, `${card.id}: y drift`);
      const frame = context === 'collection' ? { x: 50, y: 50 } : source.frames[card.visual.family];
      assert.equal(layout.x, frame.x);
      assert.equal(layout.y, frame.y);
    }
  }
  assert.deepEqual(getCardArtLayout({ family: 'unknown', icon: 'unknown' }), { x: 50, y: 44.65, offsetX: 0, offsetY: 0, scale: 1 });
});

test('art compiler rejects an unreviewed replacement and missing subject placement', async t => {
  const source = await loadJson(resolve(assetsRoot, 'card-art-layouts.json'));
  const [id, subject] = Object.entries(source.assets)[0];
  const root = await mkdtemp(resolve(LOCAL_ROOT, 'temp/card-art-compiler-'));
  await mkdir(resolve(root, 'public/assets'), { recursive: true });
  await mkdir(resolve(root, 'content'), { recursive: true });
  const fixture = { ...source, assets: { [id]: subject } };
  for (const file of [...Object.values(source.frames).map(row => row.filename), `${id}.png`]) await cp(resolve(assetsRoot, file), resolve(root, 'public/assets', file));
  const cards = [{ id: 'fixture', visual: { icon: id, family: 'strike' } }];
  await writeFile(resolve(root, 'content/cards.json'), JSON.stringify(cards));
  await writeFile(resolve(root, 'public/assets/card-art-layouts.json'), JSON.stringify(fixture));
  await compileCardArtLayouts(root, { quiet: true });
  await writeFile(resolve(root, 'public/assets', `${id}.png`), Buffer.from('changed bytes'));
  await assert.rejects(compileCardArtLayouts(root, { quiet: true }), /已改变/);
  await cp(resolve(assetsRoot, `${id}.png`), resolve(root, 'public/assets', `${id}.png`));
  cards[0].visual.icon = 'unreviewed';
  await writeFile(resolve(root, 'content/cards.json'), JSON.stringify(cards));
  await assert.rejects(compileCardArtLayouts(root, { quiet: true }), /尚未检查居中位置/);
  t.diagnostic(`Retained isolated fixture: ${root}`);
});
