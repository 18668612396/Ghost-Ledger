import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { GAME_ROOT } from './paths.mjs';

const families = ['strike', 'ward', 'spirit', 'oath'];
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
export async function compileCardArtLayouts(root = GAME_ROOT, { quiet = false } = {}) {
  const source = JSON.parse(await readFile(resolve(root, 'public/assets/card-art-layouts.json'), 'utf8'));
  if (source.version !== 1 || !source.frames || !source.assets) throw new Error('卡图定位清单格式错误。');
  const frames = {}, assets = {};
  const number = (value, min, max, path) => { if (!Number.isFinite(value) || value < min || value > max) throw new Error(`${path} 超出 ${min}–${max} 范围。`); return value; };
  async function verify(filename, sha256) {
    if (!/^[a-z0-9][a-z0-9_-]*\.png$/i.test(filename) || !/^[a-f0-9]{64}$/.test(sha256 || '')) throw new Error(`卡图定位来源无效：${filename}`);
    const bytes = await readFile(resolve(root, 'public/assets', filename));
    if (hash(bytes) !== sha256) throw new Error(`${filename} 已改变，请重新检查主体边界与居中位置。`);
  }
  for (const family of families) {
    const row = source.frames[family];
    if (!row) throw new Error(`缺少 ${family} 卡框画窗定位。`);
    await verify(row.filename, row.sha256);
    frames[family] = { x: number(row.x, 0, 100, `${family}.x`), y: number(row.y, 0, 100, `${family}.y`) };
  }
  for (const [id, row] of Object.entries(source.assets)) {
    if (!/^[a-z0-9][a-z0-9_-]*$/i.test(id) || ['constructor', 'prototype', '__proto__'].includes(id)) throw new Error(`卡图定位 id 无效：${id}`);
    await verify(`${id}.png`, row.sha256);
    assets[id] = { offsetX: number(row.offsetX, -25, 25, `${id}.offsetX`), offsetY: number(row.offsetY, -25, 25, `${id}.offsetY`), scale: number(row.scale, .5, 1.5, `${id}.scale`) };
  }
  const cards = JSON.parse(await readFile(resolve(root, 'content/cards.json'), 'utf8'));
  for (const card of cards) {
    if (!frames[card.visual?.family]) throw new Error(`${card.id} 缺少对应的卡框画窗定位。`);
    if (!Object.hasOwn(assets, card.visual?.icon)) throw new Error(`${card.id} 的主体图 ${card.visual?.icon} 尚未检查居中位置。`);
  }
  const data = { frames, assets };
  const output = `// Generated by tools/compile-card-art-layout.mjs. Edit game/public/assets/card-art-layouts.json.\nexport const CARD_ART_LAYOUTS = ${JSON.stringify(data, null, 2)};\n`;
  const path = resolve(root, 'src/generated/card-art-layout-data.js');
  await mkdir(resolve(root, 'src/generated'), { recursive: true });
  let previous = ''; try { previous = await readFile(path, 'utf8'); } catch {}
  if (previous !== output) await writeFile(path, output, 'utf8');
  if (!quiet) console.log(`${Object.keys(assets).length} 张卡图与 4 套卡框的定位、来源哈希检查通过。`);
  return { data, changed: previous !== output };
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await compileCardArtLayouts();
