import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { validateContent } from '../src/runtime/content-schema.js';

const projectRoot = fileURLToPath(new URL('..', import.meta.url));
export const TABLE_FILES = { cards: 'cards.json', powers: 'powers.json', enemies: 'enemies.json', encounters: 'encounters.json', acts: 'acts.json', events: 'events.json', visuals: 'visual-effects.json' };
export async function readContent(root = projectRoot) {
  const content = {};
  for (const [table, file] of Object.entries(TABLE_FILES)) {
    let rows;
    try { rows = JSON.parse(await readFile(resolve(root, 'content', file), 'utf8')); }
    catch (error) { throw new Error(`content/${file}：${error.message}`); }
    if (!Array.isArray(rows)) throw new Error(`content/${file} 顶层必须是数组。`);
    content[table] = {};
    for (const row of rows) {
      if (!row || !/^[a-z][a-zA-Z0-9_-]*$/.test(row.id || '') || ['constructor', 'prototype', '__proto__'].includes(row.id)) throw new Error(`content/${file} 存在非法 id。`);
      if (Object.hasOwn(content[table], row.id)) throw new Error(`content/${file} 重复 id：${row.id}`);
      content[table][row.id] = row;
    }
  }
  return content;
}
export async function compileContent(root = projectRoot, { assets = true, quiet = false } = {}) {
  const content = await readContent(root);
  const problems = validateContent(content);
  if (assets) {
    const files = new Set();
    for (const card of Object.values(content.cards)) { for (const key of ['icon', 'background', 'cost']) files.add(card.visual?.[key]); files.add(`card-frame-vivid-${card.visual?.family}`); files.add(`collection-frame-${card.visual?.family}`); }
    for (const enemy of Object.values(content.enemies)) files.add(enemy.art);
    for (const visual of Object.values(content.visuals)) if (visual.asset) files.add(visual.asset);
    for (const file of files) {
      try { const png = await readFile(resolve(root, 'public/assets', `${file}.png`)); if (png.length < 24 || png.toString('hex', 0, 8) !== '89504e470d0a1a0a') throw new Error(); }
      catch { problems.push(`素材 ${file}.png 缺失或不是有效PNG`); }
    }
  }
  if (problems.length) throw new Error(`配置校验失败：\n${problems.map(problem => `- ${problem}`).join('\n')}`);
  const json = JSON.stringify(content);
  const revision = createHash('sha256').update(json).digest('hex').slice(0, 20);
  const output = `// Generated by scripts/compile-content.mjs. Edit content/*.json, not this file.\nexport const CONTENT_REVISION = ${JSON.stringify(revision)};\nexport const CONTENT = ${JSON.stringify(content, null, 2)};\n`;
  const directory = resolve(root, 'src/generated'); await mkdir(directory, { recursive: true });
  const path = resolve(directory, 'content-data.js');
  let previous = ''; try { previous = await readFile(path, 'utf8'); } catch {}
  if (previous !== output) await writeFile(path, output, 'utf8');
  if (!quiet) console.log(`配置 ${revision}：${Object.entries(content).map(([table, rows]) => `${table} ${Object.keys(rows).length}`).join(' · ')}`);
  return { content, revision, changed: previous !== output };
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await compileContent(projectRoot, { assets: !process.argv.includes('--skip-assets') });
